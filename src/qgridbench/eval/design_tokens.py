"""Design tokens: single source of truth for figure colors, sizes, typography.

Every figure reads from here — no inline hex codes or pixel values elsewhere
(the design-token rule). MEANING is the paper's color language: one hue per meaning,
shared with the TikZ diagrams and the table rows through `latex_color_defs`.
"""

from __future__ import annotations

import matplotlib as mpl

# chart chrome only (axes and grid); every data color is a meaning color below
COLORS = {
    "neutral": "#5a5a5a",
    "grid": "#d9d9d9",
}

# Meaning colors (operator ruling, decision log 2026-11-19T16:18Z): each hue stands for one thing
# in every exhibit, the matplotlib figures, the TikZ diagrams and the table rows alike. Okabe-Ito
# hues, a published color-vision-deficiency-safe set, checked all pairs on white with the dataviz
# palette validator (worst simulated-deficiency distance 7.6, normal vision 15.6, OKLab x100). The
# 6-8 band needs a second channel, so every colored mark also carries a label or a marker shape.
MEANING = {
    "classical": "#0072B2",  # classical models
    "quantum": "#CC79A7",  # quantum models
    "attack": "#D55E00",  # the attacker: attacks, attacked inputs, attack-class rows
    "choice": "#E69F00",  # an evaluation choice as commonly made
    "control": "#009E73",  # the control that checks a choice; the leakage-free reading
    "reference": "#7F7F7F",  # data, chance floors and other references
}
# the LaTeX names the diagrams and tables use; paper/tables/design_colors.tex defines them
LATEX_COLOR_NAMES = {
    "classical": "qgClassical",
    "quantum": "qgQuantum",
    "attack": "qgAttack",
    "choice": "qgChoice",
    "control": "qgControl",
    "reference": "qgReference",
}
# light fills for table rows and box diagrams: this share of the hue, the rest white
TINT_SHARE = 0.16
QUANTUM_PREFIXES = ("qsvm", "qkernel", "vqc")
REFERENCE_PREFIXES = ("baseline_",)
# one marker per model, so a model's identity never rests on its family hue alone
MODEL_MARKERS = {
    "logreg": "v",
    "rbf_svm": "D",
    "rf": "^",
    "xgb": "s",
    "xgb_full": "s",
    "lgbm": "P",
    "mlp": "X",
    "mlp_surrogate": "X",
    "mlp_weighted": "x",
    "qsvm": "o",
    "qsvm_angle_ry": "o",
    "qkernel_angle_ry": "o",
    "qsvm_zz": "h",
    "vqc": "*",
}


def family(model_key: str) -> str:
    """'quantum', 'reference' (a chance baseline) or 'classical' for a model key."""
    if model_key.startswith(QUANTUM_PREFIXES):
        return "quantum"
    if model_key.startswith(REFERENCE_PREFIXES):
        return "reference"
    return "classical"


def family_color(model_key: str) -> str:
    return MEANING[family(model_key)]


def tint(hex_color: str, share: float = TINT_SHARE) -> str:
    """`share` of the color mixed into white, as hex (the fill behind text)."""
    rgb = [int(hex_color[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(255 - share * (255 - c)):02X}" for c in rgb)


# One outline weight for every box in every exhibit (operator ruling 2026-11-20: thin outlines
# everywhere): tinted diagram boxes, swatches, ring segments, meter and step bars, circuit gates
# and plot frames. The TikZ diagrams read it as `\dline` from the generated color file.
OUTLINE_PT = 0.3
# A box with a white fill (a circuit gate) and a plot frame have no tint to carry their shape,
# so they take the next weight up.
FRAME_PT = 0.4


def latex_color_defs() -> str:
    """`\\definecolor` lines for every meaning and its tint (`<name>Tint`), and the outline weight
    of the box diagrams (`\\dline`)."""
    lines = ["% auto-generated by qgridbench.eval.design_tokens -- do not edit by hand"]
    for key, name in LATEX_COLOR_NAMES.items():
        lines.append(f"\\definecolor{{{name}}}{{HTML}}{{{MEANING[key][1:]}}}")
        lines.append(f"\\definecolor{{{name}Tint}}{{HTML}}{{{tint(MEANING[key])[1:]}}}")
    lines.append(f"\\def\\dline{{{OUTLINE_PT}pt}}")
    return "\n".join(lines) + "\n"


# IEEE Transactions on Smart Grid (PES author kit, Part 4a): figure labels print at 8-10 pt.
# Figures are drawn at the width they are placed at (one column or the full text width), so
# native width equals placed width and every label prints at LABEL_PT.
COLUMN_WIDTH_PT = 252.0
TEXT_WIDTH_PT = 516.0
LABEL_PT = 8.0

FIGSIZE = {
    "col": (COLUMN_WIDTH_PT / 72, 3.3),  # one column: place at \columnwidth
    "col_tall": (COLUMN_WIDTH_PT / 72, 3.9),
    "text_heatmap": (
        TEXT_WIDTH_PT / 72,
        3.0,
    ),  # full-width heat map: place as figure* at \textwidth
    "text": (TEXT_WIDTH_PT / 72, 3.0),  # full text width: place at \textwidth
    "text_tall": (TEXT_WIDTH_PT / 72, 4.8),
}


def apply_style() -> None:
    mpl.rcParams.update(
        {
            # embed TrueType (42) rather than Type 3 fonts: IEEE PDF checks reject Type 3
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "figure.dpi": 150,
            "savefig.dpi": 300,
            "font.size": LABEL_PT,
            "font.family": "serif",
            "axes.titlesize": LABEL_PT,
            "axes.labelsize": LABEL_PT,
            "axes.edgecolor": COLORS["neutral"],
            "axes.linewidth": FRAME_PT,
            "xtick.major.width": FRAME_PT,
            "ytick.major.width": FRAME_PT,
            "axes.grid": True,
            "axes.axisbelow": True,  # gridlines behind bars and markers
            "grid.color": COLORS["grid"],
            "grid.linewidth": 0.5,
            "legend.fontsize": LABEL_PT,
            "lines.linewidth": 1.5,
            "xtick.labelsize": LABEL_PT,
            "ytick.labelsize": LABEL_PT,
        }
    )
